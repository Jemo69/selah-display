#!/usr/bin/env node
/**
 * speech-engine/index.js — executable entry point for the Selah
 * speech engine (Phase 2 scaffold).
 *
 * Usage:
 *   node index.js [--engine=fake|whisper|osdevice|cloud] [--host=127.0.0.1] [--port=4731]
 *                 [--bin-dir=DIR] [--models-dir=DIR] [--model=ID]
 *                 [--driver=auto|server|cli] [--allow-lan]
 *                 [--cloud-provider=openai|openrouter] [--cloud-model=ID]
 *
 * Environment (set by Selah's supervisor when it forks us):
 *   LD_SPEECH_TOKEN   per-launch secret required on every request (REQUIRED
 *                     — generated by the supervisor; never printed here)
 *   LD_SPEECH_HOST    bind host, loopback by default (127.0.0.1)
 *   LD_SPEECH_PORT    bind port, 0 = ephemeral (default 4731)
 *   LD_SPEECH_ENGINE  engine kind (default fake)
 *   LD_SPEECH_ALLOW_LAN=1  explicit trusted-LAN opt-in (same as --allow-lan)
 *   LD_SPEECH_CLOUD_PROVIDER  cloud provider: 'openai' or 'openrouter'
 *   LD_SPEECH_CLOUD_KEY       provider key, env only (never a CLI flag: the
 *                             process table is world-readable on many hosts)
 *   LD_SPEECH_CLOUD_MODEL     provider-specific model id; defaults are
 *                             'whisper-1' and 'google/gemini-2.5-flash'
 *
 * TRUSTED-LAN OPT-IN: --allow-lan / LD_SPEECH_ALLOW_LAN=1 widens the bind,
 * Origin and peer gates to a network you control, and REQUIRES an explicit
 * token (no generated fallback). The transport is plain HTTP/ws:// with NO
 * TLS: raw microphone audio crosses the network to this engine. The token is
 * a shared secret, not encryption. Default remains loopback-only.
 *
 * Modes:
 *   fake     (default) canned engine from fakeEngine.js — no model, no
 *            binary, no download. This is what makes Phase 2 verifiable, and
 *            it stays reachable ONLY when explicitly asked for.
 *   cloud    real cloud transcription. `openai` POSTs WAV to Audio
 *            Transcriptions; `openrouter` POSTs base64 WAV to the documented
 *            Responses API with a Google Gemini model. Provider + key are
 *            REQUIRED from the environment; no local binary or weights are
 *            consulted, and there is never a fallback to the canned engine.
 *   whisper  the real thing (Phase 5). A checksum-verified whisper.cpp CLI is
 *            spawned as a child process and fed WAV over stdin; see
 *            drivers/whispercpp.js for why a subprocess and not a native addon.
 *            If the binary or the weights are absent the process exits 2 with
 *            an actionable message — it never silently falls back to the canned
 *            engine, because a green "listening" badge over canned text on a
 *            sanctuary screen is the worst failure this program has.
 *
 * Security invariants enforced here and in server.js:
 *   - binds loopback ONLY (assertLoopbackBindHost throws otherwise)
 *   - token required on every request
 *   - the token is NEVER logged or printed, not even on startup
 *
 * Process protocol (fork IPC, mirrored from main/backend.js):
 *   parent <- { status: 'ready', host, port, apiVersion, wsPath }
 *   parent <- { status: 'error', error: 'EADDRINUSE', port }
 *   parent <- { t, ... }  message-bus mirror (see bus.js)
 *
 * Transports on ONE port (plan section 3):
 *   REST   /v1/...      main -> engine (health, session, transcribe)
 *   WS     /v1/stream   renderer -> engine: raw PCM frames, back to back;
 *                       engine -> renderer: the same JSON messages the
 *                       parent-process mirror forwards. Both share the
 *                       loopback bind, the launch token (header on REST,
 *                       `?token=` on the upgrade), and the bus.
 */
import { generateEngineToken, SPEECH_PROTOCOL_VERSION } from '../shared/speech/protocol.js';
import {
  createSpeechEngineServer,
  DEFAULT_BIND_HOST,
  isLanOptIn,
  LAN_OPT_IN_FLAG,
  LAN_OPT_IN_ENV,
} from './server.js';
import { attachWebSocketTransport, WS_PATH } from './wsTransport.js';
import { createFakeEngine } from './fakeEngine.js';
import path from 'node:path';
import os from 'node:os';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createWhisperEngine, hasBinary, resolveWeights, WHISPER_ROWS } from './drivers/whispercpp.js';
import { createWhisperServerEngine, hasServerBinary } from './drivers/whisperServer.js';
import { createOsDeviceEngine } from './drivers/osdevice.js';
import {
  createCloudOpenAiEngine,
  resolveCloudConfig as resolveOpenAiConfig,
} from './drivers/cloudOpenAI.js';
import {
  createCloudOpenRouterEngine,
  resolveCloudConfig as resolveOpenRouterConfig,
} from './drivers/cloudOpenRouter.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

function resolveDefaultBinDir() {
  const localBin = path.join(__dirname, "bin");
  if (hasBinary(localBin)) return localBin;
  const configHome = env.XDG_CONFIG_HOME || path.join(os.homedir(), ".config");
  const userBin = path.join(configHome, "Selah", "speech-engine", "bin");
  if (hasBinary(userBin)) return userBin;
  return localBin;
}

function resolveDefaultModelsDir() {
  const localModels = path.join(__dirname, "models");
  if (existsSync(localModels)) return localModels;
  const configHome = env.XDG_CONFIG_HOME || path.join(os.homedir(), ".config");
  const userModels = path.join(configHome, "Selah", "speech-engine", "models");
  if (existsSync(userModels)) return userModels;
  return localModels;
}
import { createMessageBus } from './bus.js';

function parseArgs(argv) {
  const out = {};
  for (const arg of argv) {
    const match = /^--([a-zA-Z-]+)(?:=(.*))?$/.exec(arg);
    if (match) out[match[1]] = match[2] === undefined ? true : match[2];
  }
  return out;
}

const args = parseArgs(process.argv.slice(2));
const env = process.env;

/**
 * Where the engine's binary and weights live.
 *
 * Resolved from the supervisor's environment, with the documented drop-in
 * directory as the fallback — the same layout main/speechDownloader.js writes
 * (`<userData>/speech-engine/`). Both are parameters so a test can point them
 * anywhere.
 */
const binDir = String(args['bin-dir'] ?? env.LD_SPEECH_BIN_DIR ?? resolveDefaultBinDir());
const modelsDir = String(args['models-dir'] ?? args.modelsDir ?? env.LD_SPEECH_MODELS_DIR ?? resolveDefaultModelsDir());

// Default to whisper if either driver is installed and at least one model has
// weights; otherwise fallback to fake.
const defaultEngine = ((hasBinary(binDir) || hasServerBinary(binDir)) && WHISPER_ROWS.some((m) => Boolean(resolveWeights(modelsDir, m.id))))
  ? 'whisper'
  : 'fake';

const engineKind = String(args.engine ?? env.LD_SPEECH_ENGINE ?? defaultEngine);

/**
 * Cloud launch config. Provider and model may come from a flag or the
 * environment; the key is read from the environment ONLY, because a
 * `--cloud-key=...` flag would expose it to every local process listing.
 *
 * resolveCloudConfig throws with an actionable `code` for a missing/unknown
 * provider or key. buildEngine() turns that into exit 2 — fail loudly, never
 * a local engine wearing a cloud label.
 */
let cloudConfig = null;
if (engineKind === 'cloud') {
  try {
    const provider = args['cloud-provider'] ?? env.LD_SPEECH_CLOUD_PROVIDER;
    const model = args['cloud-model'] ?? env.LD_SPEECH_CLOUD_MODEL;
    const common = { provider, apiKey: env.LD_SPEECH_CLOUD_KEY, model };
    if (provider === 'openai') cloudConfig = resolveOpenAiConfig(common);
    else if (provider === 'openrouter') cloudConfig = resolveOpenRouterConfig(common);
    else {
      throw Object.assign(new Error('Only openai and openrouter cloud providers are supported.'), {
        code: 'cloud-provider-not-supported',
      });
    }
  } catch (error) {
    // The message names the missing setting, never the key or any audio.
    console.error(`speech-engine: ${error.message}`);
    process.exit(2);
  }
}

const host = String(args.host ?? env.LD_SPEECH_HOST ?? DEFAULT_BIND_HOST);
const port = Number(args.port ?? env.LD_SPEECH_PORT ?? 4731);
/**
 * LAN exposure is an explicit operator decision, never implied by a host
 * value. Both the flag and the env form require an explicit token: a
 * generated secret cannot be shared with a second machine, so a LAN bind
 * with a generated token would be an unusable (and unauditable) posture.
 */
const allowLan = args[LAN_OPT_IN_FLAG.slice(2)] === true || isLanOptIn(env[LAN_OPT_IN_ENV]);
const explicitToken = typeof args.token === 'string' && args.token.length >= 16
  ? args.token
  : (typeof env.LD_SPEECH_TOKEN === 'string' && env.LD_SPEECH_TOKEN.length >= 16
      ? env.LD_SPEECH_TOKEN
      : null);
if (allowLan && !explicitToken) {
  console.error(
    'speech-engine: --allow-lan requires LD_SPEECH_TOKEN (or --token) of at least 16 characters. ' +
      'No token is generated for a LAN bind. Trusted LAN only: no TLS, raw audio crosses the network.'
  );
  process.exit(2);
}
const token = explicitToken ?? generateEngineToken();

const bus = createMessageBus();

/**
 * Build the engine this run was asked for.
 *
 * WHY A REAL ENGINE FAILS LOUDLY AND LOUDLY HERE. If `--engine=whisper` is
 * requested and the binary or the weights are missing, the process exits 2 with
 * a message naming what to install. It does NOT fall back to the canned engine.
 *
 * That fallback is the single most dangerous thing this program could do: a
 * green "listening" badge attached to a process emitting a string it wrote
 * itself, on a sanctuary screen, during a service. `src/speech/engineTruth.js`
 * exists to make that unreachable in the UI, and this is the other half of the
 * same rule — make it unreachable in the engine.
 *
 * @returns {object} an engine implementing the v1 contract
 */
function buildEngine() {
  if (engineKind === 'cloud') {
    // Resolved (and validated) before the server binds: a cloud launch with
    // no key is a configuration error, not a reason to start whisper.
    if (cloudConfig.provider === 'openrouter') {
      return createCloudOpenRouterEngine({
        bus,
        apiKey: cloudConfig.apiKey,
        model: cloudConfig.model,
      });
    }
    return createCloudOpenAiEngine({
      bus,
      apiKey: cloudConfig.apiKey,
      model: cloudConfig.model,
      language: typeof args.lang === 'string' ? args.lang : (env.LD_SPEECH_LANG || undefined),
    });
  }

  if (engineKind === 'fake') return createFakeEngine({ bus });

  if (engineKind === 'whisper') {
    const requestedDriver = String(args.driver ?? env.LD_SPEECH_DRIVER ?? 'auto').toLowerCase();
    if (!['auto', 'server', 'cli'].includes(requestedDriver)) {
      console.error(`speech-engine: unknown driver "${requestedDriver}". Use auto, server, or cli.`);
      process.exit(2);
    }
    const useServer = requestedDriver === 'server'
      || (requestedDriver === 'auto' && hasServerBinary(binDir));
    try {
      if (useServer) {
        return createWhisperServerEngine({
          bus,
          binDir,
          modelsDir,
          modelId: typeof args.model === 'string' ? args.model : (env.LD_SPEECH_MODEL || undefined),
          language: typeof args.lang === 'string' ? args.lang : (env.LD_SPEECH_LANG || undefined),
        });
      }
      return createWhisperEngine({
        bus,
        binDir,
        modelsDir,
        modelId: typeof args.model === 'string' ? args.model : (env.LD_SPEECH_MODEL || undefined),
      });
    } catch (error) {
      const detail = error?.code === 'unavailable'
        ? 'The whisper.cpp binary or its model weights are not installed. Use the ' +
          '"Install speech engine" button in Settings, or run with --engine=fake.'
        : 'The whisper.cpp engine could not be initialised.';
      console.error(`speech-engine: ${detail}`);
      process.exit(2);
    }
  }

  if (engineKind === 'osdevice') {
    // The constructor probes the platform itself and throws ENGINE_UNAVAILABLE
    // with the remedy when there is no OS backend here — same fail-loud rule
    // as whisper, never a silent fallback to the canned engine.
    try {
      // Language rides the same env/flag convention as the whisper model id
      // below. Nothing in the app sets it yet (every session is 'auto' =
      // the default recognizer); it exists so a test or a launcher can.
      return createOsDeviceEngine({
        bus,
        language: typeof args.lang === 'string' ? args.lang : (env.LD_SPEECH_LANG || undefined),
      });
    } catch (error) {
      // error.message already embeds the probe's actionable reason
      // (missing PowerShell vs missing recognizer) — printing the generic
      // support line here would strand the remedy in a discarded string.
      const detail = error?.code === 'unavailable' && error?.message
        ? error.message
        : 'The OS speech engine could not be initialised.';
      console.error(`speech-engine: ${detail}`);
      process.exit(2);
    }
  }

  // An unknown engine name is a configuration error, and guessing at one is
  // exactly how a typo becomes a wrong engine mid-service.
  console.error(`speech-engine: unknown engine "${engineKind}". Use "fake", "whisper", "osdevice", or "cloud".`);
  process.exit(2);
  return null;
}

// Parent-process mirror: Selah's supervisor subscribes over the fork
// IPC channel and relays recognized messages to the renderer. The WebSocket
// transport below subscribes to the SAME bus — one emission point, two sinks,
// so a renderer WebSocket drop never loses the transcript log.
bus.subscribe((message) => {
  if (typeof process.send === 'function') {
    try {
      process.send(message);
    } catch {
      // Parent went away; the HTTP surface keeps serving.
    }
  }
});

const handle = createSpeechEngineServer({
  token,
  host,
  allowLan,
  bus,
  engine: buildEngine(),
});

// The renderer's PCM ingest: same loopback server, same token, same bus —
// attached only after the REST surface bound successfully. The bus is the
// single emission point (see bus.js), so everything a WebSocket client sees
// is byte-for-byte what the parent-process mirror sends to Selah.
const stream = attachWebSocketTransport(handle.server, {
  token,
  bus,
  engine: handle.engine,
  host,
  allowLan,
});

const shutdown = () => {
  try {
    stream.close();
  } catch {
    // best effort — the HTTP close below is the real gate
  }
  if (typeof handle.engine?.close === 'function') {
    try { handle.engine.close(); } catch {}
  }
  handle
    .close()
    .catch(() => {})
    .finally(() => process.exit(0));
  // Safety net: never hang a shutdown the supervisor is escalating.
  setTimeout(() => process.exit(0), 1000).unref();
};

process.on('SIGTERM', shutdown);
process.on('SIGINT', shutdown);

handle
  .listen(port, host)
  .then(({ port: boundPort, host: boundHost }) => {
    // No token in this line — logs must never carry secrets.
    console.log(
      `speech-engine [${engineKind}] listening on http://${boundHost}:${boundPort}` +
        (allowLan ? ' (TRUSTED LAN OPT-IN — no TLS, audio crosses the network)' : '')
    );
    if (typeof process.send === 'function') {
      process.send({
        status: 'ready',
        host: boundHost,
        port: boundPort,
        apiVersion: SPEECH_PROTOCOL_VERSION,
        // Where the renderer dials in (plan section 3): the supervisor and
        // the renderer must agree on ONE path constant.
        wsPath: WS_PATH,
      });
    }
  })
  .catch((error) => {
    if (error?.code === 'EADDRINUSE') {
      if (typeof process.send === 'function') {
        process.send({ status: 'error', error: 'EADDRINUSE', port });
      }
      console.error(`speech-engine: port ${port} is already in use`);
      process.exit(1);
    }
    // Loopback refusal and bind failures land here, loudly and non-zero.
    console.error(`speech-engine: failed to start: ${error.message}`);
    if (typeof process.send === 'function') {
      process.send({ status: 'error', error: error.code || 'bind-failed', message: error.message });
    }
    process.exit(1);
  });
